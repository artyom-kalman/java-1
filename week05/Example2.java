void main() {
    boolean b1 = true;
    boolean b2 = false;
    boolean b3 = true;

    System.out.println(b1 && b2);
    System.out.println(b1 && b3);
    System.out.println(b1 || b2);
    System.out.println(b1 ^ b2);
    System.out.println(b1 ^ b3);
    System.out.println(!b1);
    System.out.println(!!b2);
}
