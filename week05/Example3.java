void main() {
    int a = 5;
    int b = -3;

    System.out.printf("%d < %d is %b\n", a, b, a < b);
    System.out.printf("%d == %d is %b\n", a, b, a == b);
    System.out.printf("%d != %d is %b\n", a, b, a != b);
    System.out.printf("%d > %d is %b\n", a, b, a > b);
    System.out.printf("%d <= %d is %b\n", a, b, a <= b);
    System.out.printf("%d >= %d is %b\n", a, b, a >= b);
}
